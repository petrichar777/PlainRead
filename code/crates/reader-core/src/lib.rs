//! 简阅 · PlainRead 内核。
//!
//! 本 crate 是项目的**领域层与基础设施层**，刻意的约束是：
//!
//! - **不依赖任何 UI 框架**（tauri / egui / web 全都不能出现在依赖树里）
//! - **不依赖任何表现层概念**（不知道"页面"、"窗口"、"IPC" 是什么）
//!
//! 这条约束不是洁癖，它买到两样东西：
//!
//! 1. **可测**：内核的全部逻辑都能在没有窗口、没有 GPU 的环境下单元测试。
//! 2. **可替换**：UI 技术栈变更时这一层不需要改动。
//!    本项目已经因此受益一次——从自绘方案切换到 Tauri 方案时，本 crate 一行未改。
//!
//! # 两条核心不变式
//!
//! 后续实现分页与进度时，必须始终成立：
//!
//! 1. **不丢字**：从存储读出的章节文本，与规范化后的原文逐字符一致。
//! 2. **进度往返**：按字符偏移定位到的页，反过来能还原出同一个字符偏移。

pub mod domain;
pub mod infra;

pub use domain::*;

/// 内核版本号。外壳与前端在自检信息里会展示它，
/// 用于快速判断"跑的是哪个版本的内核"。
pub const VERSION: &str = env!("CARGO_PKG_VERSION");
